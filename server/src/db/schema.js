// Database schema and in-place upgrades. Idempotent; runs under an advisory lock so several
// app tasks starting together (rolling deploy across AZs) don't race each other.
import { pool } from './pool.js';
import { logger } from '../logger.js';
import { STATUSES, ROLES, LEGACY_STATUS, LEGACY_ROLE } from '../domain/workflow.js';

const SCHEMA = `
CREATE TABLE IF NOT EXISTS users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username text UNIQUE NOT NULL,
  name text NOT NULL,
  role text NOT NULL,
  district text,                               -- NULL = statewide
  password_hash text NOT NULL,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS sessions (
  token text PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES users(id),
  expires_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_sessions_expires ON sessions(expires_at);

-- Nurse IDs (UYIR-NUR-000001) come from a sequence: safe with many app servers.
CREATE SEQUENCE IF NOT EXISTS nurse_no_seq;

CREATE TABLE IF NOT EXISTS nurses (
  id text PRIMARY KEY,
  name text NOT NULL,
  mobile text NOT NULL UNIQUE,
  district text NOT NULL,
  source text,
  status text NOT NULL DEFAULT 'NEW',
  stage_reached smallint NOT NULL DEFAULT 0,
  assigned_to bigint REFERENCES users(id),
  call_attempts integer NOT NULL DEFAULT 0,      -- outcomes logged by the calling team
  last_contacted_at timestamptz,

  -- consent & contact preferences
  dnc boolean NOT NULL DEFAULT false,
  dnc_reason text,
  dnc_at timestamptz,
  consent_call boolean NOT NULL DEFAULT true,    -- phone calls from the calling team
  consent_sms boolean NOT NULL DEFAULT true,
  consent_whatsapp boolean NOT NULL DEFAULT false,
  consent_data_processing_at timestamptz,
  preferred_language text DEFAULT 'ta',

  -- registration portal
  reg_token text UNIQUE,
  reg_session text,
  reg_session_expires timestamptz,
  otp_hash text,
  otp_expires timestamptz,
  otp_attempts integer NOT NULL DEFAULT 0,
  mobile_verified_at timestamptz,
  registered_at timestamptz,

  -- registration details
  email text, address text, taluk text, block text,
  qualification text, council_reg_no text, current_employment text,
  experience_years double precision, work_preference text, preferred_locations text, service_interests text,

  -- payment details (onboarding, after verification); account number encrypted at rest
  payout_account_holder text,
  payout_account_enc text,
  payout_account_last4 text,
  payout_ifsc text,
  payout_upi text,
  payout_added_at timestamptz,

  review_note text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_nurses_district_status ON nurses(district, status);
CREATE INDEX IF NOT EXISTS ix_nurses_status ON nurses(status);
CREATE INDEX IF NOT EXISTS ix_nurses_district_stage ON nurses(district, stage_reached);
CREATE INDEX IF NOT EXISTS ix_nurses_assigned ON nurses(assigned_to);

CREATE TABLE IF NOT EXISTS events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nurse_id text NOT NULL REFERENCES nurses(id),
  at timestamptz NOT NULL DEFAULT now(),
  type text NOT NULL,           -- status | call | sms | note | document | registration | consent | import
  from_status text, to_status text,
  note text,
  user_id bigint REFERENCES users(id),
  actor text                    -- 'system', 'nurse', 'automation' or username
);
CREATE INDEX IF NOT EXISTS ix_events_nurse ON events(nurse_id, id);

CREATE TABLE IF NOT EXISTS documents (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nurse_id text NOT NULL REFERENCES nurses(id),
  type text NOT NULL,
  filename text NOT NULL,
  mime text NOT NULL,
  stored_name text NOT NULL,                   -- object key in the storage driver
  storage text NOT NULL DEFAULT 'local',       -- 'local' | 's3'
  sha256 text,
  size integer NOT NULL,
  status text NOT NULL DEFAULT 'SUBMITTED',    -- SUBMITTED | VERIFIED | CORRECTION | REJECTED | SUPERSEDED
  note text,
  uploaded_at timestamptz NOT NULL DEFAULT now(),
  reviewed_by bigint REFERENCES users(id),
  reviewed_at timestamptz
);
CREATE INDEX IF NOT EXISTS ix_documents_nurse ON documents(nurse_id);

-- Outbound messages. A gateway worker would send rows with status 'queued';
-- in this prototype they are written as 'simulated'.
CREATE TABLE IF NOT EXISTS messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nurse_id text NOT NULL REFERENCES nurses(id),
  channel text NOT NULL,
  template text NOT NULL,
  body text NOT NULL,
  status text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
-- SMS → WhatsApp invite flow: the SMS carries a wa.me link with the nurse's code; when the
-- nurse messages us we record their WhatsApp number and reply with the registration link.
ALTER TABLE nurses ADD COLUMN IF NOT EXISTS wa_code text;
ALTER TABLE nurses ADD COLUMN IF NOT EXISTS whatsapp_number text;
ALTER TABLE nurses ADD COLUMN IF NOT EXISTS whatsapp_connected_at timestamptz;
ALTER TABLE nurses ADD COLUMN IF NOT EXISTS whatsapp_last_inbound_at timestamptz;
CREATE UNIQUE INDEX IF NOT EXISTS ux_nurses_wa_code ON nurses(wa_code) WHERE wa_code IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_nurses_whatsapp_number ON nurses(whatsapp_number) WHERE whatsapp_number IS NOT NULL;

-- Every incoming WhatsApp message (Meta may deliver a webhook twice: wa_message_id dedupes).
CREATE TABLE IF NOT EXISTS whatsapp_inbound (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  wa_message_id text NOT NULL UNIQUE,
  from_number text NOT NULL,
  profile_name text,
  body text,
  nurse_id text REFERENCES nurses(id),
  outcome text,                                -- linked | matched | unmatched | dnc | duplicate
  at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_whatsapp_inbound_nurse ON whatsapp_inbound(nurse_id);

-- Replies to unknown WhatsApp senders belong to no nurse.
ALTER TABLE messages ALTER COLUMN nurse_id DROP NOT NULL;

-- Delivery tracking (WhatsApp worker + delivery-status webhook).
ALTER TABLE messages ADD COLUMN IF NOT EXISTS payload jsonb;
ALTER TABLE messages ADD COLUMN IF NOT EXISTS attempts integer NOT NULL DEFAULT 0;
ALTER TABLE messages ADD COLUMN IF NOT EXISTS next_attempt_at timestamptz NOT NULL DEFAULT now();
ALTER TABLE messages ADD COLUMN IF NOT EXISTS provider_id text;
ALTER TABLE messages ADD COLUMN IF NOT EXISTS error text;
ALTER TABLE messages ADD COLUMN IF NOT EXISTS sent_at timestamptz;
ALTER TABLE messages ADD COLUMN IF NOT EXISTS updated_at timestamptz NOT NULL DEFAULT now();
CREATE INDEX IF NOT EXISTS ix_messages_nurse ON messages(nurse_id);
CREATE INDEX IF NOT EXISTS ix_messages_status ON messages(status) WHERE status = 'queued';
CREATE INDEX IF NOT EXISTS ix_messages_due ON messages(next_attempt_at) WHERE status = 'queued' AND channel = 'whatsapp';
CREATE INDEX IF NOT EXISTS ix_messages_provider ON messages(provider_id) WHERE provider_id IS NOT NULL;
-- Nurses who start on WhatsApp (SMS chat link → "Hi") get a record before anyone knows their
-- district; they choose it in the registration form. Until then only Super Admins see them.
ALTER TABLE nurses ALTER COLUMN district DROP NOT NULL;
-- Session clean-up when a user's access changes.
CREATE INDEX IF NOT EXISTS ix_sessions_user ON sessions(user_id);
`;

// The app only collects nurse information (no CRM). Upgrade data from the CRM version in place:
// map old statuses to the new ones (history kept, a note added), recompute progress, map staff roles.
async function toInfoCollection(c) {
  const old = Object.keys(LEGACY_STATUS);
  const caseStatus = `CASE status ${old.map(s => `WHEN '${s}' THEN '${LEGACY_STATUS[s]}'`).join(' ')} END`;
  const caseStage = `CASE ${caseStatus} ${Object.entries(STATUSES).map(([k, s]) => `WHEN '${k}' THEN ${s.stage}`).join(' ')} END`;
  await c.query('BEGIN');
  try {
    const moved = await c.query(`WITH m AS (
        UPDATE nurses n SET status = ${caseStatus}, stage_reached = ${caseStage}
        FROM (SELECT id, status AS old_status FROM nurses WHERE status = ANY($1) FOR UPDATE) o
        WHERE n.id = o.id RETURNING n.id, o.old_status, n.status)
      INSERT INTO events (nurse_id, type, from_status, to_status, note, actor)
        SELECT id, 'status', old_status, status, 'Upgraded to information-collection workflow', 'system' FROM m
      RETURNING 1`, [old]);
    const roles = await c.query(`UPDATE users SET role = CASE role ${Object.entries(LEGACY_ROLE).map(([a, b]) => `WHEN '${a}' THEN '${b}'`).join(' ')}
        ELSE 'district_admin' END,
        active = active AND role IN (${Object.keys(LEGACY_ROLE).map(r => `'${r}'`).join(',')})
      WHERE role NOT IN (${Object.keys(ROLES).map(r => `'${r}'`).join(',')}) RETURNING username, role, active`);
    await c.query(`ALTER TABLE nurses ALTER COLUMN status SET DEFAULT 'NEW'`);
    await c.query('COMMIT');
    if (moved.rowCount) logger.info({ count: moved.rowCount }, 'nurses moved to the information-collection statuses');
    for (const u of roles.rows) logger.info({ username: u.username, role: u.role, active: u.active }, 'legacy staff role converted');
  } catch (e) { await c.query('ROLLBACK'); throw e; }
}

/** Re-run the CRM → information-collection upgrade (used after copying old SQLite data in). */
export async function upgradeLegacyData() {
  const c = await pool.connect();
  try { await toInfoCollection(c); } finally { c.release(); }
}

export async function migrate() {
  const c = await pool.connect();
  try {
    await c.query(`SELECT pg_advisory_lock(727001)`);
    await c.query(SCHEMA);
    await toInfoCollection(c);
    // Fast name / ID search (ILIKE '%…%'). Optional: needs CREATE privilege for extensions (rds_superuser has it).
    try {
      await c.query(`CREATE EXTENSION IF NOT EXISTS pg_trgm`);
      await c.query(`CREATE INDEX IF NOT EXISTS ix_nurses_name_trgm ON nurses USING gin (name gin_trgm_ops)`);
    } catch (e) { logger.warn({ err: e.message }, 'pg_trgm not available; name search will scan'); }
  } finally {
    await c.query(`SELECT pg_advisory_unlock(727001)`).catch(() => {});
    c.release();
  }
}
